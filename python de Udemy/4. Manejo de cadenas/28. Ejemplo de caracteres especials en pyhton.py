# Progama: ejemplo de caracteres especiales en pyhton

# Salto de linea \n
mensaje1 = "hola\nmundo"
print(mensaje1)

# Tabulacion \t
# Imprimimios una guia numerica para ver la posicon
print("12341234123412341234")
mensaje2 = "\tJuan perez"
mensaje3 = "\t\tJuan perez"
print(mensaje2)
print(mensaje3)

# Comillas dentro de cadenas
mensaje4 = "Ella dijo \"Hola a todos\""
print(mensaje4)

# Barra invertida \
mensaje5 = "c:\\Usuarios\\marce\\docemntos"
print(mensaje5)

# Cadenas cruda (raw string) r
mensaje6 = r"C:\usuario\marce\documentos"
print(mensaje6)

