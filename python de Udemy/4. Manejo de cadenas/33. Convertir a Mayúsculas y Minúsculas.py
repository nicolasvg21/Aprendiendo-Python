# Programa: # Funcion mayuscula y minuscula

entrada = "Python"

# Convertir a mayuscula
grito = entrada.upper()
print(grito) # Salida: "PYTHON"

# Convertir a minuscula (estandarizar)
bajito = entrada.lower()
print(bajito) # Salida "python"

# La original sigue intacta
print(entrada) # Salida: "Python"



