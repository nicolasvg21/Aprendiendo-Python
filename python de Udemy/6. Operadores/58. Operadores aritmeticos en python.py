#Operadores aritmeticos

a = 10 
b = 3

#suma +
suma = a + b
print(f"suma: {suma}")

#resta - 
resta = a - b
print(f"resta: {resta}")

#multiplicacion *
multiplicacion = a * b
print(f"multiplicacion: {multiplicacion}")

#division /
division = a / b
print(f"division: {division:.2f}")

#division que da un enetero //
division_entera = a // b
print(f"division entera: {division_entera}")

#operador de modulo % (residuo de la division)
division_modulo = a % b
print(f"Residuo de la divison de modulo: { division_modulo}")

# Exponente (potenciacion) **
exponente = a ** b   # 10^3=1000
print(f"Exponente: {exponente}")
