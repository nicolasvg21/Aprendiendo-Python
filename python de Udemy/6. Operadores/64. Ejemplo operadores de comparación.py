print("**** Operardores de comparacion ****")
a, b = 5, 5 
print(f"Valor inciail a: {a}, b: {b}")

# Operador igualdad ==
resultado = (a == b)
print(resultado)

# Operador diferente 1=
resultado = a != b
print(resultado)

# Operador mayor que >
resultado = a != b
print(resultado)

# Operador mayor o igual que >=
resultado = a >= b
print(resultado)

# Operador menor que <
resultado = a < b
print(resultado)

# Operador menor o igual que <=
resultado = a <= b
print(resultado)